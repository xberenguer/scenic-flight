//! Authored building volumes. All coordinates are within the surveyed lot.
use super::Tier;

pub(crate) struct Landmark {
    pub name: &'static str,
    pub size: [f32; 2],
    pub height: f32,
    pub wall: [u8; 3],
    pub masses: &'static [Tier],
}

const fn mass(x: f32, z: f32, width: f32, depth: f32, top: f32) -> Tier {
    span(x, z, width, depth, 0.0, top)
}

const fn span(x: f32, z: f32, width: f32, depth: f32, bottom: f32, top: f32) -> Tier {
    Tier {
        bottom,
        top,
        half: [width, depth],
        center: [x, z],
    }
}

const fn building(
    name: &'static str,
    width: f32,
    depth: f32,
    height: f32,
    material: usize,
    masses: &'static [Tier],
) -> Landmark {
    Landmark {
        name,
        size: [width, depth],
        height,
        wall: super::WALLS[material],
        masses,
    }
}

